export const LANGUAGES = [
  { code: "en", label: "English" },
  { code: "lv", label: "Latviešu" },
  { code: "de", label: "Deutsch" },
  { code: "es", label: "Español" },
];

const LANG_KEY = "tempmail:lang";
let current = "en";
const listeners = new Set();

function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function t(key, vars) {
  const dict = DICTS[current] || DICTS.en;
  const val = dict[key] ?? DICTS.en[key] ?? key;
  return interpolate(val, vars);
}

export function getLang() {
  return current;
}

export function setLang(code) {
  if (!DICTS[code]) code = "en";
  current = code;
  try {
    localStorage.setItem(LANG_KEY, code);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = code;
  applyStaticTranslations();
  listeners.forEach((fn) => fn(code));
}

export function onLangChange(fn) {
  listeners.add(fn);
}

/** Fill elements that carry data-i18n / data-i18n-title / data-i18n-ph / data-i18n-aria. */
export function applyStaticTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
}

export function initLang() {
  let stored = null;
  try {
    stored = localStorage.getItem(LANG_KEY);
  } catch {
    /* ignore */
  }
  const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
  setLang(stored || (DICTS[nav] ? nav : "en"));
}
